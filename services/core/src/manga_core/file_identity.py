"""同じ 1 つのファイルを指す綴りを、1 つの鍵へ揃える。

``Path.resolve()`` はシンボリックリンクを解くだけで、**別名（ハードリンク）も
大文字小文字の違いも解かない**。配布先の Windows は大文字小文字を区別しない
ので、``D:\\蔵書\\本.zip`` と ``D:\\蔵書\\本.ZIP`` は同じ 1 つのファイルだが、
解いた形は別々のままになる。パスの形を鍵にすると、同じファイルが 2 つの
別物として通る。

そうなると症状が 2 つ出る。依頼の検証（``manga_api.organize_job``）が、片方の
綴りに名前・もう片方に巻数の訂正を載せた依頼を素通しする。投入の展開
（``manga_core.input_expander``）が同じ実体を 2 回返し、同じ本が ``_1`` 付きで
2 冊出来る。どちらも利用者から見ると「頼んでいないことが起きた」だけで、
綴りが 2 つに割れたせいだとは読めない。

鍵の作り方はここ 1 か所に置く。投入の展開と依頼の検証が別々に鍵を作ると、
片方だけ直したときに門と実処理が別の本を指す。
"""

from collections.abc import Hashable
from pathlib import Path


def file_key(path: str | Path) -> Hashable:
    """このパスが指す**実体**の鍵。同じファイルの別の綴りは同じ鍵になる。

    ファイルシステムが言う識別子（``st_dev`` と ``st_ino``）で照合する。
    ``os.path.samefile`` が使うのと同じ組で、Windows でも取れる（``st_ino`` は
    ファイル索引、``st_dev`` はボリューム通し番号）。

    実体を確かめられないときは、リンクを解いたパスをそのまま鍵にする。**黙って
    落とさない。** 整理の対象は必ず実在するが、鍵を作る段では依頼に書かれた
    文字列でしかないので実在は保証されない。照合しようが無いものは、今までと
    同じく綴りごとに別物として扱う。
    """
    resolved = Path(path).resolve()
    try:
        info = resolved.stat()
    except OSError:
        return resolved
    if not info.st_ino:
        # 識別子を返さないファイルシステム（一部のネットワーク共有）。0 を
        # そのまま鍵にすると**全てのファイルが 1 つの実体に畳まれる**ので、
        # 綴りが割れるより桁違いに悪い。パスの側へ退く
        return resolved
    return (info.st_dev, info.st_ino)
