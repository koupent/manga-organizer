"""重い処理を途中で止めるための、コア層の合図（#80 段階 A）。

``manga_core`` は ``manga_api`` を取り込まない。取り込むと GUI 非依存のコアが
サイドカーの都合に縛られる。それでも「いま上がったこの例外は打ち切りだ」を
見分けられないと、コア層は打ち切りを壊れたアーカイブと同じ網で握りつぶす。
実際 ``toc_analyzer._NESTED_READ_ERRORS`` には ``RuntimeError`` が入っており、
``manga_api.jobs.JobCancelled`` がその一種であるために、利用者が解析を止めても
入れ子を最後まで読み切り、しかもその打ち切りが「目次を読めません」という嘘の
印に化けていた。

そこで概念だけを下の層に置き、``JobCancelled`` にこれを継がせる。
``BaseException`` にして網から外す手もあるが、そちらは
``FileOrganizer.process_single_archive`` の 1 冊ごとの ``except Exception`` など
無関係な場所の振る舞いまで黙って変える。ここは継承 1 本で済ませ、握りつぶさ
ないことは受け止める順番で保証する。
"""


